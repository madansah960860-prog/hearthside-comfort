      <h2>Where the information comes from</h2>
      <ul>
        <li><strong>Directly from you</strong> — when you order online, by
        telephone or by mail, contact us, or ask about a return.</li>
        <li><strong>Automatically from your device</strong> — standard web
        server logs and, if enabled, analytics.</li>
        <li><strong>From our service providers</strong> — for example the
        carrier confirming a delivery, or the payment provider confirming a
        payment succeeded.</li>
      </ul>

      <h2>Service providers we share information with</h2>
      <p>We share only what each one needs to do its job. None of them may use
      your information for their own marketing.</p>
      <ul>
        <li><strong>Payment processor</strong> — takes the payment. It receives
        your card details directly on its own page; we never receive them.</li>
        <li><strong>Shipping carriers</strong> (USPS, UPS, FedEx) — receive your
        name, delivery address and telephone number in order to deliver.</li>
        <li><strong>Hosting provider</strong> — stores the site and its server
        logs.</li>
        <li><strong>Email provider</strong> — sends order confirmations and
        replies to your messages.</li>
      </ul>
      <p>We also disclose information where the law requires it, or to protect
      our legal rights. <strong>We do not sell personal information, and we do
      not share it for cross-context behavioural advertising.</strong></p>

      <h2>Cookies and Google advertising tools</h2>
      <p>Details of each cookie category are in our
      <a href="cookie-policy.php">Cookie Policy</a>.</p>
      <p>This store advertises itself through Google Ads and lists products
      through Google Merchant Center. Where Google conversion tracking or
      remarketing is enabled, Google may set cookies or similar identifiers in
      your browser so that a purchase can be attributed to an advertisement, or
      so that our advertisements can be shown to you on other sites.</p>
      <p>You can opt out of personalised Google advertising at
      <a href="https://adssettings.google.com" rel="nofollow noopener">Google Ad
      Settings</a>, and opt out of many other advertisers at
      <a href="https://optout.aboutads.info" rel="nofollow noopener">optout.aboutads.info</a>
      and <a href="https://optout.networkadvertising.org"
      rel="nofollow noopener">optout.networkadvertising.org</a>. Opting out does
      not stop you seeing advertisements; it stops them being personalised.</p>
      <p>We do not run third-party display advertising on this site. There are
      no advertising slots anywhere on it.</p>

      <h2>Your California rights</h2>
      <p>Under the California Consumer Privacy Act as amended by the California
      Privacy Rights Act, if you are a California resident you have the right
      to:</p>
      <ul>
        <li><strong>Know</strong> what personal information we have collected
        about you, where it came from, why we collected it, and who we
        disclosed it to.</li>
        <li><strong>Delete</strong> the personal information we hold about you,
        subject to exceptions such as completing a transaction or meeting a
        legal or tax obligation.</li>
        <li><strong>Correct</strong> inaccurate personal information.</li>
        <li><strong>Opt out of the sale or sharing</strong> of your personal
        information. We do not sell or share it in the first place, but the
        right exists and you may exercise it — see
        <a href="your-privacy-choices.php">Your Privacy Choices</a>.</li>
        <li><strong>Limit the use of sensitive personal information.</strong> We
        do not collect any.</li>
        <li><strong>Not be discriminated against</strong> for exercising any of
        these rights. We will not refuse service, change prices, or give you a
        worse experience because you asked.</li>
      </ul>
      <p>You may make a request yourself or through an authorised agent. We
      verify requests by matching the details you give us against an order —
      normally the name, email address and order date. We respond within
      <strong>45 days</strong>, and may extend once by a further 45 days if we
      tell you why.</p>

      <h2>Global Privacy Control</h2>
      <p><strong>We honor Global Privacy Control signals.</strong> If your
      browser or extension sends a GPC signal, we treat it as a valid request
      to opt out of any sale or sharing of your personal information, for that
      browser, without you needing to do anything else.</p>

      <h2>Rights in other states</h2>
      <p>Residents of <strong>Virginia, Colorado, Connecticut, Utah, Texas and
      Oregon</strong> have comparable rights under their own state privacy laws
      — to access, correct, delete and obtain a copy of their personal
      information, and to opt out of targeted advertising, sale, and certain
      profiling. Several of these states also give you the right to appeal a
      refused request. To exercise any of them, or to appeal, use the contact
      details at the foot of this page and tell us which state you live in. We
      apply the same process and the same 45-day response time to everyone.</p>

      <h2>Children</h2>
      <p>This site is not directed to children under 13 and we do not knowingly
      collect personal information from them. If you believe a child has given
      us information, contact us and we will delete it.</p>

      <h2>How long we keep information</h2>
      <ul>
        <li><strong>Order records</strong> — seven years, to meet tax and
        accounting requirements.</li>
        <li><strong>Email correspondence</strong> — two years.</li>
        <li><strong>Server logs</strong> — 90 days.</li>
        <li><strong>Checkout form submissions</strong> — not retained at all
        while online payment is unavailable.</li>
      </ul>

      <h2>Security</h2>
      <p>The site is served over HTTPS. Access to order records is limited to
      the people who need it to pack orders and answer the telephone. Card
      details never reach our systems — they go directly to the payment
      provider. No method of transmission or storage is perfectly secure, and
      we will not pretend otherwise.</p>

      <h2>Changes to this policy</h2>
      <p>If we change it we will update the effective date at the top of this
      page. If the change is significant we will say so on the home page for at
      least 30 days.</p>

