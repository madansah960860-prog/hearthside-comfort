      <h1>Return &amp; Refund Policy</h1>
      <p><strong>Effective date:</strong> September 22, 2026</p>
    </div>
    <div class="prose">
      <p>If something is not right, send it back. You have
      <strong>30 days from the day your parcel is delivered</strong>,
      return shipping is free, and there is no restocking fee.</p>

      <h2>The return window</h2>
      <p>30 calendar days, counted from the delivery date shown by
      the carrier — not from the date you ordered and not from the date we
      shipped. If the carrier's delivery date is wrong, tell us and we will use
      the date you actually received it.</p>

      <h2>What condition the item needs to be in</h2>
      <p>Unworn or lightly tried on, clean, and with any tags still attached.
      Trying a garment on indoors is expected and is not a problem — that is
      what the return window is for. An item that has been worn outdoors,
      washed, altered or damaged cannot be returned unless it was faulty.</p>

      <h2>Items that are final sale</h2>
      <p>For hygiene reasons, the following are final sale <strong>once the
      sealed pack has been opened</strong>. Unopened packs can be returned like
      anything else.</p>
      <ul>
        <li>Non-Slip Gripper Socks, 3-Pack (HC-1007)</li>
        <li>Non-Binding Comfort Socks, 6-Pack (HC-1008)</li>
        <li>Graduated Compression Socks (HC-1009)</li>
        <li>Snap-Shoulder Cotton Undershirt (HC-1019)</li>
        <li>Cozy Sleep Socks, 2-Pack (HC-1029)</li>
        <li>Thermal Crew-Neck Undershirt (HC-1044)</li>
      </ul>
      <p>Every one of those items says so plainly on its own product page,
      above the fold, before you buy. Nothing else we sell is final sale.</p>

      <h2>How to start a return</h2>
      <p>Any of these three. You do not need an account and you do not need to
      log in to anything.</p>
      <ul>
        <li><strong>Email</strong> <a href="mailto:help@hearthsidecomfort.com">help@hearthsidecomfort.com</a> with
        your name and the item number. We reply within one business day with a
        prepaid label.</li>
        <li><strong>Telephone</strong> <a href="tel:+14045550142">(404) 555-0142</a> during
        Mon–Fri 9 AM–6 PM ET. We can post a printed label to you if you would rather not
        print one.</li>
        <li><strong>Write to us</strong> at Hearthside Comfort Co. LLC, 1847 Mercer Way, Suite 120, Alpharetta,
        GA 30009, with a note of your name and the item number.</li>
      </ul>

      <h2>Who pays for return shipping</h2>
      <p><strong>We do.</strong> We provide a prepaid label for every standard
      return within the window, at no cost to you.</p>

      <h2>Restocking fee</h2>
      <p><strong>There is no restocking fee.</strong> We do not charge one on
      any item, for any reason. We are stating that explicitly because a
      restocking fee buried in a policy is one of the more common unpleasant
      surprises in online retail.</p>

      <h2>If an item arrives damaged, faulty or wrong</h2>
      <p>Tell us within 30 days of delivery by telephone or email. A
      photograph helps but is not required.</p>
      <ul>
        <li>We reply within <strong>one business day</strong>.</li>
        <li>We ship a replacement within <strong>1–2 business days</strong> of
        agreeing it, or refund you in full if you would rather.</li>
        <li>You do not have to send the item back before we act, and you never
        pay shipping either way.</li>
        <li>If you prefer a refund, it is issued within <strong>three to five
        business days</strong> of us agreeing it.</li>
      </ul>

      <h2>How refunds are paid</h2>
      <p>To the original payment method, always. We do not issue store credit
      in place of a refund, and we will not offer you a voucher instead of your
      money.</p>
      <p><strong>Timing:</strong> we process the refund within <strong>three
      business days</strong> of your return arriving with us. Your bank or card
      issuer then takes its own time to show it, usually <strong>five to ten
      business days</strong>. We will tell you the day we send it.</p>

      <h2>Exchanges</h2>
      <p>Tell us the size or item you want instead and we will send it as soon
      as your return is on its way back to us — you do not have to wait for it
      to arrive here first. If there is a price difference we will tell you
      before anything is sent. Exchanges carry no shipping charge in either
      direction.</p>

      <h2>Cancelling an order before it ships</h2>
      <p>Telephone <a href="tel:+14045550142">(404) 555-0142</a> or email
      <a href="mailto:help@hearthsidecomfort.com">help@hearthsidecomfort.com</a>. If the parcel has not left us, we
      cancel it and refund you in full, to your original payment method, with
      nothing deducted. Once it has shipped, treat it as a normal return — and
      we will still cover the return shipping.</p>

      <h2>If we cannot ship on time</h2>
      <p>Under the Federal Trade Commission's Mail, Internet, or Telephone
      Order Merchandise Rule (16 CFR Part 435), if we cannot ship within the
      time we stated, we will contact you, tell you the new date, and give you
      the choice of accepting the delay or cancelling. If you cancel, you get a
      <strong>full refund to your original payment method</strong> — not store
      credit. Details are in our
      <a href="shipping-policy.php">Shipping Policy</a>.</p>

      <h2>How to reach us about this policy</h2>
      <p>Hearthside Comfort Co. LLC<br>
      1847 Mercer Way, Suite 120<br>
      Alpharetta, GA 30009<br>
      Telephone: <a href="tel:+14045550142">(404) 555-0142</a> (Mon–Fri 9 AM–6 PM ET)<br>
      Email: <a href="mailto:help@hearthsidecomfort.com">help@hearthsidecomfort.com</a></p>
