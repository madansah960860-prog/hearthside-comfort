    <div class="prose">
      <p>A cookie is a small text file a website asks your browser
      to keep. This page explains the three categories that may be used here
      and what each one is for.</p>

      <h2>Essential cookies</h2>
      <p>These make the site work. They remember things like your browser's
      security session. The site cannot function without them and they cannot
      be switched off from within the site.</p>
      <p>Note that this store has <strong>no shopping basket and no
      accounts</strong>, so there is no cookie remembering what you were buying
      or who you are. Everything in an order happens on a single page.</p>

      <h2>Analytics cookies</h2>
      <p>If enabled, these tell us which pages are visited and how people move
      through the site, in aggregate. We use that to find pages that are
      confusing or broken. They do not tell us your name, address or telephone
      number.</p>

      <h2>Advertising cookies</h2>
      <p>This store advertises through Google Ads and lists products through
      Google Merchant Center. If conversion tracking or remarketing is enabled,
      Google may set cookies so that:</p>
      <ul>
        <li>a purchase can be attributed to the advertisement you clicked, and</li>
        <li>our advertisements can be shown to you on other websites.</li>
      </ul>
      <p>You can turn off personalised Google advertising at
      <a href="https://adssettings.google.com" rel="nofollow noopener">Google Ad
      Settings</a>. <strong>We do not run third-party display advertising on
      this site</strong> — there are no advertising slots on any page here.</p>

      <h2>Controlling cookies in your browser</h2>
      <p>Every major browser lets you see, block and delete cookies. The
      settings are usually under Privacy or Security:</p>
      <ul>
        <li><strong>Chrome</strong> — Settings, then Privacy and security, then
        Third-party cookies.</li>
        <li><strong>Safari</strong> — Settings, then Privacy.</li>
        <li><strong>Edge</strong> — Settings, then Cookies and site
        permissions.</li>
        <li><strong>Firefox</strong> — Settings, then Privacy &amp; Security.</li>
      </ul>
      <p>Blocking essential cookies may stop parts of the site working.
      Blocking analytics and advertising cookies will not affect your ability to
      browse or order.</p>
      <p>If your browser sends a <strong>Global Privacy Control</strong> signal
      we honour it — see <a href="your-privacy-choices.php">Your Privacy
      Choices</a>.</p>

