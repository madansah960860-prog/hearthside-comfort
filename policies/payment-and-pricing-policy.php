      <h1>Payment &amp; Pricing Policy</h1>
      <p><strong>Effective date:</strong> September 22, 2026</p>
    </div>
    <div class="prose">
      <div class="notice">
        <p><strong>Online payment is being set up and is not switched on
        yet.</strong> You can fill in the checkout and press Place order — it
        will always work — but no order can be completed online and nothing is
        charged. To complete an order today, telephone
        <a href="tel:+14045550142">(404) 555-0142</a> during Mon–Fri 9 AM–6 PM ET, or use the mail-in
        form on our <a href="../pages/how-to-order.php#mail">How to Order</a>
        page.</p>
      </div>

      <h2>How we will accept payment</h2>
      <p>When online payment is live, it will be taken on the payment
      provider's own hosted page:</p>
      <ul>
        <li>Credit and debit cards, on the payment provider's secure page</li>
        <li>PayPal</li>
      </ul>
      <p><strong>We never ask for a card number on this website.</strong> There
      are no card number, expiry, security code or billing address fields
      anywhere on this site, and there never will be. Card details belong on
      the payment provider's own page and nowhere else. If any page here ever
      asks you for a card number, it is not ours — close it and telephone
      us.</p>
      <p>For telephone orders we take payment over the phone, and for mail
      orders by check payable to Hearthside Comfort Co. LLC. <strong>Never post cash and never
      write a card number on the mail-in form.</strong></p>

      <h2>Listed prices include all mandatory fees</h2>
      <p>The price you see on a product page is the whole price of that item.
      There is no handling charge, no service fee, no processing fee and no
      compulsory extra of any kind hiding at the end of the checkout.</p>
      <p>The only two things added are:</p>
      <ul>
        <li><strong>Shipping</strong>, which you choose, and which is shown
        before you order: $6.95 standard or free over
        $75, $18.95 expedited.</li>
        <li><strong>Sales tax</strong>, which is a government tax we are
        required to collect.</li>
      </ul>
      <p>This follows California's Honest Pricing Law (SB 478, Civil Code
      &sect;1770(a)(29)), which prohibits advertising a price that does not
      include all mandatory charges. We apply it to every customer in every
      state, because it is the right way to quote a price.</p>

      <h2>Sales tax</h2>
      <p>Sales tax is <strong>calculated at checkout based on your delivery
      state</strong>, at the rate in force for that address on the day you
      order. We show the amount before you confirm. Tax is collected on behalf
      of the state and passed to it; we keep none of it.</p>

      <h2>Price changes</h2>
      <p>Prices can change. The price that applies to your order is the one
      shown when you place it. If a price changes after you order but before we
      ship, we honour the price you were shown.</p>

      <h2>No fictitious former prices</h2>
      <p><strong>You will not see a crossed-out &ldquo;was&rdquo; price
      anywhere on this site.</strong></p>
      <p>A former price is only honest if the item was genuinely offered at
      that price, openly, for a reasonably substantial period. This store has
      only just opened and has no price history at all, so any crossed-out
      price here would be invented. The FTC's Guides Against Deceptive Pricing
      (16 CFR &sect;233.1) prohibit exactly that, and we would not do it
      regardless.</p>
      <p>If we run a genuine sale in future, the former price will be one the
      item was actually sold at, for a real and stated period.</p>

      <h2>Coupons and bundles</h2>
      <p>We do not currently issue coupon codes. If we ever do, the terms and
      the expiry date will be printed in full on the offer itself.</p>
      <p>The bundles on our <a href="../pages/deals.php">Today's Deals</a>
      page are <strong>not discounted sets</strong>. Each item in them is at its
      normal everyday price; they are simply three things that go together and
      that happen to clear the $75 free-shipping threshold. We say
      so on that page too.</p>

      <h2>Currency</h2>
      <p>All prices are in U.S. dollars.</p>

      <h2>When something is charged</h2>
      <p>Once online payment is live, your card will be authorised when you
      place the order and charged when the order ships. For telephone and mail
      orders we confirm the total with you before taking anything.</p>

