      <h2>Recall monitoring</h2>
      <p>We monitor U.S. Consumer Product Safety Commission recall notices for
      the categories we sell. If an item you bought from us is recalled, we will
      contact you using the details from your order and tell you what to do.</p>
      <p>You can check for yourself at
      <a href="https://www.cpsc.gov/Recalls" rel="nofollow noopener">cpsc.gov/Recalls</a>.
      To report an unsafe product to us directly, telephone
      <a href="tel:+14045550142">(404) 555-0142</a> — we would rather hear about it early.</p>

      <h2>California Proposition 65</h2>
      <p>Proposition 65 requires a warning before purchase for products that can
      expose Californians to certain listed chemicals. Our approach is to record
      a status for <em>every</em> product we sell, and to show the warning
      wherever it is required.</p>
      <ul>
        <li><strong>Warning shown:</strong> the
        <a href="../products/heated-throw-auto-shut-off.php">Heated Throw
        (HC-1033)</a>, because of the plasticiser used in its power cord. The
        warning appears on its product page, above the buy button, before you
        purchase.</li>
        <li><strong>Confirm with supplier</strong> — status not yet verified,
        and therefore no warning claimed either way: Large-Face Analog Wristwatch
        (HC-1053), RFID Cross-Body Wallet (HC-1054), Auto-Open Compact Umbrella
        (HC-1055).</li>
        <li><strong>Not required:</strong> every other item, all of which are
        textiles or footwear with no listed-chemical component identified.</li>
      </ul>
      <p>The per-product status is recorded in our <code>catalog.md</code> file
      and is reviewed whenever a supplier changes. For more information see
      <a href="https://www.P65Warnings.ca.gov" rel="nofollow noopener">www.P65Warnings.ca.gov</a>.</p>

