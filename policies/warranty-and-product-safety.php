      <h2>Limited warranty</h2>
      <p>We warrant every item against defects in materials and workmanship for
      <strong>one year from the date of delivery</strong>. If something fails
      because it was badly made, we replace it or refund you, at your choice,
      and we pay the shipping both ways.</p>
      <p>The warranty does not cover normal wear — a sole worn smooth over a
      year of daily walking, a knit that has pilled, elastic that has relaxed
      after long use — nor damage from misuse, alteration, or failure to follow
      the care instructions on the product page.</p>

      <h3>How to claim</h3>
      <ol>
        <li>Telephone <a href="tel:+14045550142">(404) 555-0142</a> during Mon–Fri 9 AM–6 PM ET, or email
        <a href="mailto:help@hearthsidecomfort.com">help@hearthsidecomfort.com</a>.</li>
        <li>Tell us the item number and what has gone wrong. A photograph
        helps but is not required.</li>
        <li>We respond within one business day and, if it is a warranty fault,
        send a replacement within 1–2 business days or refund you within three to
        five business days.</li>
      </ol>
      <p>This warranty gives you specific legal rights. You may have other
      rights which vary from state to state, and nothing here limits them.</p>

      <h2>Safety notices by category</h2>

      <h3>Heated products with a power cord</h3>
      <p>Applies to the <a href="../products/heated-throw-auto-shut-off.php">Heated
      Throw with Auto Shut-Off (HC-1033)</a>.</p>
      <ul>
        <li>Do not use on anyone who cannot move unaided or who cannot feel heat
        normally, and never on an infant.</li>
        <li>Do not fold, bunch or tuck in the throw while it is switched on, and
        do not sleep under it.</li>
        <li>Do not use together with a hot water bottle.</li>
        <li>Inspect the cord, controller and fabric before every use. Stop using
        it if the fabric is scorched, a wire is exposed, or the controller is
        damaged.</li>
        <li>Unplug it when it is not in use, and detach the controller before
        washing.</li>
        <li>Prolonged contact with any heated surface can burn skin even at low
        temperatures.</li>
      </ul>
      <p><strong>Auto shut-off:</strong> three hours on every setting. It cannot
      be disabled.<br>
      <strong>Power:</strong> 120 V AC, 60 Hz, 115 W. Cord length 9 ft.</p>
      <p><strong>Safety listing:</strong> we have <em>not</em> independently
      verified any UL or ETL listing for this product, and we therefore make no
      such claim. Its status is recorded in our catalog as
      <strong>&ldquo;confirm with supplier&rdquo;</strong>. We would rather tell
      you that than print a certification mark we cannot stand behind.</p>

      <h3>Compression socks</h3>
      <p>Applies to <a href="../products/graduated-compression-socks.php">Graduated
      Compression Socks, 15&ndash;20 mmHg (HC-1009)</a>.</p>
      <p><strong>Ask your doctor before using compression socks, especially if
      you have diabetes, circulation problems, or any condition affecting the
      skin of your legs or feet.</strong> Stop wearing them and speak to a
      clinician if you notice numbness, discolouration, or pain. We state the
      compression class and nothing more; we make no claim about circulation,
      swelling, clots, or any other medical matter.</p>

      <h3>Weighted blanket</h3>
      <p>Applies to the <a href="../products/weighted-blanket-12-lb.php">12-lb
      Weighted Blanket (HC-1050)</a>.</p>
      <ul>
        <li><strong>Never use it on a child or an infant.</strong></li>
        <li><strong>Never use it for anyone who cannot remove it unaided</strong>,
        who cannot move freely in bed, or who cannot communicate discomfort.</li>
        <li>Never place it over the head or face.</li>
        <li>Ask your doctor first if you have a respiratory or circulatory
        condition, sleep apnoea, or limited mobility.</li>
        <li>Choose roughly ten per cent of body weight. Heavier is not
        better.</li>
      </ul>

      <h3>Cushions, pillows and footwear</h3>
      <p>We describe these products by their physical properties only —
      dimensions, foam density, shape, sole construction. <strong>We make no
      claim that any of them relieves pain, improves posture, or is orthopaedic
      or therapeutic.</strong> If you have been given advice by a physician or
      an occupational therapist about seating, footwear or positioning, follow
      that advice rather than anything on a product page here, and ask them
      before changing what you use.</p>
      <p>Adding a cushion to a chair raises you and changes how you get in and
      out of it. Take the first few sits slowly.</p>
      <p>Slip-resistant soles reduce slipping; they do not make a floor safe,
      and nothing grips ice. Replace footwear when the tread has worn
      smooth.</p>

      <h3>Garments containing magnets</h3>
      <p>Applies to the
      <a href="../products/mens-magnetic-button-shirt.php">Men's
      Magnetic-Button Shirt (HC-1013)</a> and the
      <a href="../products/womens-magnetic-front-blouse.php">Women's
      Magnetic-Front Blouse (HC-1014)</a>.</p>
      <p>These garments contain magnets. <strong>Keep them away from
      pacemakers, implanted defibrillators and other implanted medical
      devices</strong>, and ask the device manufacturer or your doctor about safe
      distances before wearing one. Keep them away from magnetic-stripe cards
      and hotel key cards.</p>

      <h3>Sleepwear and loose garments</h3>
      <p>Our sleepwear is <strong>not flame resistant</strong>. Keep loose
      garments clear of gas hobs, open fires and portable heaters. Fleece is a
      synthetic and will melt rather than char.</p>

