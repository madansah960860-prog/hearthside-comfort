      <h1>Your Privacy Choices</h1>
      <p><strong>Effective date:</strong> September 22, 2026</p>
    </div>
    <div class="prose">
      <div class="notice">
        <p><strong>Hearthside Comfort Co. LLC does not sell your personal information, and
        does not share it for cross-context behavioural advertising.</strong>
        There is nothing you need to do to stop it.</p>
        <p>You still have the right to tell us to opt you out, and this page
        explains how. You do not need an account and you will never be asked to
        create one.</p>
      </div>

      <h2>Three ways to opt out</h2>
      <h3>1. Global Privacy Control — automatic, nothing to fill in</h3>
      <p>If your browser or a browser extension sends a
      <strong>Global Privacy Control</strong> signal, we treat it as a valid
      opt-out request for that browser and we act on it immediately. You do not
      have to contact us and we do not need to know who you are. GPC is
      supported by several browsers and extensions; see
      <a href="https://globalprivacycontrol.org" rel="nofollow noopener">globalprivacycontrol.org</a>.</p>

      <h3>2. Email</h3>
      <p>Write to <a href="mailto:help@hearthsidecomfort.com">help@hearthsidecomfort.com</a> with the subject line
      <strong>&ldquo;Do Not Sell or Share&rdquo;</strong>. Tell us the name and
      email address or telephone number you used when you contacted or ordered
      from us, so we can find you.</p>

      <h3>3. Telephone</h3>
      <p>Call <a href="tel:+14045550142">(404) 555-0142</a> during Mon–Fri 9 AM–6 PM ET and say you want
      to opt out. A person will take the request there and then. If you would
      rather do it in writing, post it to Hearthside Comfort Co. LLC, 1847 Mercer Way, Suite 120, Alpharetta,
      GA 30009.</p>

      <h2>What happens after you ask</h2>
      <ol>
        <li>We acknowledge your request within <strong>10 business days</strong>
        and tell you what we are doing about it.</li>
        <li>We record the opt-out against your details so it stays in
        force.</li>
        <li>We complete the request and confirm in writing within
        <strong>45 days</strong>. If we need longer we will tell you why, and we
        may extend once by a further 45 days.</li>
      </ol>
      <p>A GPC signal takes effect straight away, with no acknowledgement step,
      because we do not know who sent it.</p>

      <h2>We will not treat you differently</h2>
      <p>Opting out costs you nothing. We will not refuse to serve you, charge
      you a different price, give you a lower level of service, or remove any
      benefit because you exercised a privacy right. That is required by
      California Civil Code &sect;1798.125, and it is also simply how we intend
      to behave.</p>

      <h2>Authorised agents</h2>
      <p>You may use an authorised agent to make a request for you. We will ask
      the agent for written permission signed by you, and we may contact you
      directly to confirm that you gave it. If the agent holds a valid power of
      attorney under California Probate Code sections 4000 to 4465, that is
      sufficient on its own and we will not ask you separately.</p>

      <h2>Other privacy requests</h2>
      <p>To know what we hold, to correct it, or to delete it, use the same
      three routes above. Those rights, and the rights of residents of Virginia,
      Colorado, Connecticut, Utah, Texas and Oregon, are set out in our
      <a href="privacy-policy.php">Privacy Policy</a>.</p>

