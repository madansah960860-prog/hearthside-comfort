      <h1>Accessibility Statement</h1>
      <p><strong>Effective date:</strong> September 22, 2026</p>
    </div>
    <div class="prose">
      <p>This store is built for shoppers aged 60 and over, so
      accessibility is not an afterthought here — it is most of the design
      brief.</p>

      <h2>Our target</h2>
      <p>We aim to meet <strong>Web Content Accessibility Guidelines (WCAG) 2.1
      at Level AA</strong>, and we exceed it in several places, most notably
      text contrast.</p>

      <h2>What we have done</h2>
      <table>
        <caption>Accessibility features built into this site</caption>
        <tbody>
          <tr><th scope="row">Large type</th>
            <td>Body text is 19px and never smaller than 16px anywhere,
              including footer and legal text. At narrow widths the layout
              reflows — the text does not shrink.</td></tr>
          <tr><th scope="row">Contrast</th>
            <td>Body text is 14.8:1 against the page background, which exceeds
              the 7:1 required at Level AAA. Button text is 14.3:1.</td></tr>
          <tr><th scope="row">Underlined links</th>
            <td>Every link is underlined, so colour is never the only way to
              tell a link from text.</td></tr>
          <tr><th scope="row">Real buttons</th>
            <td>Every button is at least 48px tall with a written label. No icon
              appears anywhere without a word next to it.</td></tr>
          <tr><th scope="row">Keyboard</th>
            <td>Everything works from the keyboard, including the whole
              checkout. There is a visible 4px focus ring on every control and a
              skip link to the main content.</td></tr>
          <tr><th scope="row">Nothing moves</th>
            <td>No carousels, no auto-rotating banners, no autoplay, no
              countdown timers, no infinite scroll, and no pop-ups or modals
              anywhere on the site.</td></tr>
          <tr><th scope="row">No hover-only menus</th>
            <td>Every navigation link is a real link that works by tap, click
              and keyboard.</td></tr>
          <tr><th scope="row">Alt text</th>
            <td>Every photograph that carries information has descriptive
              alternative text. Decorative images are marked so screen readers
              skip them.</td></tr>
          <tr><th scope="row">Reduced motion</th>
            <td>We respect the <code>prefers-reduced-motion</code> setting.
              There is almost no motion to begin with.</td></tr>
          <tr><th scope="row">Print</th>
            <td>Product pages, How to Order and the mail-in form print cleanly
              in black on white, with link addresses shown.</td></tr>
          <tr><th scope="row">Form errors</th>
            <td>Errors appear only after you have finished with a field, say how
              to fix it in plain words, and use a thicker border and an icon as
              well as colour.</td></tr>
        </tbody>
      </table>

      <h2>Known limitations</h2>
      <p>We would rather list these than pretend they are not there.</p>
      <ul>
        <li><strong>The feature filter needs a recent browser.</strong> It is
        built with the CSS <code>:has()</code> selector. In an older browser
        the filter simply does nothing and <em>all</em> products stay visible —
        nothing is hidden and nothing is lost, but the narrowing will not
        work.</li>
        <li><strong>There is no search results page.</strong> With no server to
        search with, the search box takes you to the Shop All page, where you
        browse by department, by feature, or through the A&ndash;Z list. If that
        is awkward, telephone us and we will find the item for you.</li>
        <li><strong>Size tables are wide.</strong> On a narrow phone some size
        tables need horizontal scrolling within the table itself. We are looking
        at a better layout for these.</li>
        <li><strong>Photographs are stock photography.</strong> Alternative text
        describes what is in each picture accurately, but the pictures are not
        of the exact unit you will receive.</li>
      </ul>

