    <div class="prose">
      <h2>Where we ship</h2>
      <p>All 50 states and the District of Columbia. We also ship to APO, FPO
      and DPO addresses; those go by USPS and typically take longer than the
      estimates below — allow an extra one to three weeks.</p>
      <p>Alaska and Hawaii are shipped at the same rates as the rest of the
      country, but expedited delivery is not available to either, and standard
      delivery usually takes an extra two to four business days.</p>
      <p><strong>We do not ship internationally.</strong> We would rather say
      that plainly than take an order we cannot fulfil.</p>

      <h2>Processing time</h2>
      <p>We pack and hand over your parcel within <strong>1–2 business days</strong>
      of your order being confirmed. Orders confirmed at a weekend or on a
      federal holiday are processed on the next business day.</p>

      <h2>Delivery estimates and costs</h2>
      <table>
        <caption>Shipping methods, cost and delivery time</caption>
        <thead>
          <tr><th scope="col">Method</th><th scope="col">Cost</th>
            <th scope="col">Arrives after shipping</th></tr>
        </thead>
        <tbody>
          <tr><th scope="row">Standard</th>
            <td>$6.95, or <strong>free on orders over
              $75</strong> before tax</td>
            <td>3–7 business days</td></tr>
          <tr><th scope="row">Expedited</th>
            <td>$18.95 — not included in the free-shipping
              threshold</td>
            <td>2–3 business days</td></tr>
          <tr><th scope="row">APO / FPO / DPO</th>
            <td>$6.95, or free over $75</td>
            <td>3–7 business days plus one to three weeks</td></tr>
        </tbody>
      </table>
      <p>Delivery times are business days and are counted <em>after</em> the
      parcel leaves us, so add the processing time above. They are the
      carrier's estimates, not guarantees.</p>

      <h2>The free-shipping threshold</h2>
      <p>Free standard shipping applies when the value of the items in your
      order is more than <strong>$75</strong>, calculated before
      sales tax. It is not a limited-time promotion and there is no end
      date.</p>

      <h2>Carriers</h2>
      <p>USPS, UPS or FedEx, whichever serves your address best. We choose;
      you cannot specify a carrier. APO, FPO and DPO addresses always go by
      USPS.</p>

      <h2>Tracking</h2>
      <p>We email a tracking number as soon as the carrier collects your
      parcel. It usually starts updating within one business day. If you did
      not give us an email address, telephone <a href="tel:+14045550142">(404) 555-0142</a>
      and we will read it out to you. There is no account to log in to.</p>

      <h2>If we cannot ship on time — your rights</h2>
      <p>The Federal Trade Commission's Mail, Internet, or Telephone Order
      Merchandise Rule (16 CFR Part 435) applies to this store. Under it:</p>
      <ul>
        <li>We must ship within the time we stated. Where no time is stated,
        the law assumes <strong>30 days</strong>.</li>
        <li>If we cannot, we must <strong>notify you</strong>, give you a
        revised shipping date, and offer you the choice of accepting the delay
        or cancelling the order.</li>
        <li>If you cancel, we must refund you <strong>in full, to your original
        payment method</strong>. Not store credit, not a voucher, not a partial
        refund.</li>
        <li>If you do not respond to a notice of delay, we cancel the order and
        refund you.</li>
      </ul>
      <p>We will contact you by telephone and by email, and we will act on
      whichever answer reaches us first.</p>

      <h2>Lost or damaged parcels</h2>
      <p>If tracking shows no movement for <strong>five business days</strong>,
      or shows delivered when nothing arrived, telephone or email us. We open a
      claim with the carrier ourselves — that is our job, not yours — and we
      will either resend the order or refund you in full. We do not make you
      wait for the carrier's investigation to finish before we put it right.</p>
      <p>If a parcel arrives visibly damaged, photograph it before opening if
      you can, then contact us. See our
      <a href="return-and-refund-policy.php">Return &amp; Refund Policy</a>.</p>

      <h2>Address errors</h2>
      <p>We ship to the address you give us. Please check it before you order.
      If you spot a mistake, telephone us straight away — if the parcel has not
      gone we will simply correct it at no charge.</p>
      <p>If a parcel is returned to us as undeliverable because of an incorrect
      address, we will contact you and reship it once the address is corrected.
      We charge the standard shipping rate again for the second attempt, and we
      will tell you before we do. If the error was ours, we reship free.</p>

