      <h2>Tracking an order</h2>
      <p>We email a tracking number from the carrier as soon as your parcel is
      collected. It usually starts showing movement within one business day.</p>
      <ol class="prose">
        <li>Check the shipping confirmation email for the tracking number.</li>
        <li>Enter it on the carrier's own website, which is linked in the same
        email.</li>
        <li>If there is no movement after three business days, call
        <a href="tel:+14045550142">(404) 555-0142</a> and we will chase the carrier
        ourselves.</li>
      </ol>
      <p>If you did not give us an email address when you ordered, telephone us
      and we will read the tracking number out to you. There is no account to
      log in to, and you never need one.</p>
    </section>

    <section class="band">
      <h2>Questions we are asked most</h2>
      <p>These are our own answers. They are not customer reviews.</p>
      <details>
        <summary>How do I know which size to order?</summary>
        <p>Every product page has a size table in inches with the finished measurements, plus instructions for measuring. The most reliable method is to measure a garment you already like laid flat, rather than measuring yourself. If you are between two sizes, size up. If you would rather do it with someone on the phone, call us.</p>
      </details>
      <details>
        <summary>Can I order without using the website?</summary>
        <p>Yes. Telephone (404) 555-0142 during Mon–Fri 9 AM–6 PM ET and a person will take the order. Or print the mail-in form on the How to Order page and post it with a check. You never need an account for any route.</p>
      </details>
      <details>
        <summary>Why did my online order not go through?</summary>
        <p>Online payment is not switched on yet, so no order placed on this site can be completed and nothing is ever charged. That is not a problem with your card or your bank — no card details are asked for anywhere on this site. Call us and we will complete the order.</p>
      </details>
      <details>
        <summary>How do I track my order?</summary>
        <p>When your order ships we email a tracking number from the carrier. If you did not give us an email address, call us and we will read the number out. Tracking usually starts updating within one business day of the parcel being collected.</p>
      </details>
      <details>
        <summary>How long do I have to return something?</summary>
        <p>30 days from the day it is delivered. Return shipping is free and there is no restocking fee. Sealed socks, undershirts and other undergarments are final sale once the pack is opened; unopened packs can be returned like anything else.</p>
      </details>
      <details>
        <summary>What does the return cost me?</summary>
        <p>Nothing, for a standard return within the window. We email a prepaid label, or post one to you if you would rather. If an item arrived damaged, faulty or wrong, we cover everything and you do not need to return it before we send a replacement.</p>
      </details>
      <details>
        <summary>Do you add fees at checkout?</summary>
        <p>No. The price on the product page includes every mandatory fee. The only things added at checkout are shipping, which is shown before you order, and sales tax, which is calculated from your delivery state. There are no handling charges and no service fees.</p>
      </details>
      <details>
        <summary>Do you ship outside the United States?</summary>
        <p>No. We ship to all 50 states, the District of Columbia, and APO, FPO and DPO addresses. We do not ship internationally at the moment.</p>
      </details>
      <details>
        <summary>Are the products certified as safe?</summary>
        <p>We state only what we can prove. Where a safety listing such as UL or ETL has not been independently verified by us, the product page says so and records the status as &#x27;confirm with supplier&#x27;. We would rather tell you that than print a certification we cannot stand behind.</p>
      </details>
      <details>
        <summary>Will you sell my personal information?</summary>
        <p>No. We do not sell or share personal information, and we honour Global Privacy Control signals. See Your Privacy Choices in the footer of every page.</p>
      </details>
    </section>

