      <div class="prose">
        <h2>Who this store is for</h2>
        <p>For people who have found that getting dressed has quietly become
        the most tiring part of the morning. Buttons get smaller every year.
        Zips need two hands and good light. A shoe that has to be threaded onto
        a foot means sitting down, bending over, and getting back up again.</p>
        <p>None of that is a medical problem and we do not treat it as one.
        It is a design problem, and it has been solved over and over by people
        who make adaptive clothing — it is just that most of what they make is
        sold as equipment rather than as clothes. We would rather sell it as
        clothes.</p>
      </div>
    </div>

    <section class="band">
      <div class="prose">
        <h2>How we choose what to sell</h2>
        <p>Every item here has to pass three tests before it goes on the site.</p>
        <ol>
          <li><strong>Can it be put on while seated, with one hand if
          possible?</strong> If a garment needs two steady hands, good light and
          a mirror, it does not belong in this store.</li>
          <li><strong>Does it look like ordinary clothing?</strong> A magnetic
          shirt with visible plastic fittings is a medical garment. A magnetic
          shirt with real buttons stitched over the magnets is a shirt. We only
          stock the second kind.</li>
          <li><strong>Can we describe it honestly in plain words?</strong> If
          the only way to make something sound appealing is to imply it will
          help with a condition, we do not stock it.</li>
        </ol>

        <h2>What we will not tell you</h2>
        <p>We will not tell you that anything here treats, relieves, prevents or
        improves any medical condition. Compression socks are described by their
        compression class and nothing more. A seat cushion is described by its
        shape, its foam density and its dimensions. A weighted blanket is
        described by its weight and its fill. What any of those things do for
        you is a conversation for you and a clinician.</p>
        <p>We also will not tell you how long we have been trading, how many
        customers we have, or what anyone has said about us, because a new store
        cannot prove any of it. When verified customers have written reviews,
        their reviews will appear on the product pages and not before.</p>

        <h2>Sizes, and getting them right</h2>
        <p>Almost every return in a clothing shop is a sizing return, and almost
        every sizing return could have been avoided with a tape measure and two
        minutes. So every product page carries a size table in inches, the
        actual finished measurements rather than a vague letter, and
        instructions for measuring a garment you already own instead of
        measuring yourself.</p>
        <p>If you would rather do it with someone, call
        <a href="tel:+14045550142">(404) 555-0142</a> during Mon–Fri 9 AM–6 PM ET and we will work
        through it with you. That is not a sales line — it is the same people
        who pack the boxes.</p>

        <h2>How to reach a person</h2>
        <p>Telephone <a href="tel:+14045550142">(404) 555-0142</a>, Mon–Fri 9 AM–6 PM ET. Email
        <a href="mailto:help@hearthsidecomfort.com">help@hearthsidecomfort.com</a>, answered within one business day.
        Or write to us at Hearthside Comfort Co. LLC, 1847 Mercer Way, Suite 120, Alpharetta, GA 30009.</p>
        <p>The store is run by Ruth Ellery, who answers the email.</p>
