      <div class="prose">
        <p>The layer that does most of the work in cold weather and that nobody sees. It is a waffle knit — a honeycomb structure that holds pockets of air against the skin — which is why a thin thermal is warmer than a thick plain cotton shirt. Because the warmth comes from the structure rather than the thickness, it fits under an ordinary shirt without bulk at the shoulder or the cuff. The body is cut two inches longer than a standard undershirt. That is a deliberate choice: a short thermal pulls out of the waistband every time you reach up to a shelf, and then the small of your back is the coldest part of you. Sleeves are full length with a ribbed cuff that stays at the wrist rather than riding up a forearm. The seams at the shoulder are flat. A shirt collar and a coat both sit directly on the shoulder seam, and a raised overlocked seam under them is felt all day. The neck is a ribbed crew, stretchy enough to go over the head without catching. The fabric is a cotton-polyester blend — cotton against the skin, polyester for recovery so it does not stretch out at the elbow. Machine wash warm, tumble dry low.</p>
