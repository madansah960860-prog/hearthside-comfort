    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>This is the shoe for the days when bending down is the hard part. The heel counter is sprung: there is a curved plastic band moulded into the back that folds flat when you put your weight on it and springs upright again once your heel is past it. You put your toe in, step down, and the shoe closes behind you. No hands, no shoehorn, nothing to pull. Because slip-ons usually solve entry and then fit badly, this one has elastic gores let into both sides under the eyestay. They take up the slack across the instep so the shoe holds on while you walk rather than pistoning at the heel. The laces you can see are decorative and stitched down; there is nothing to tie and nothing that can come loose. The last is wide through the forefoot in both D and EE, with a toe box that keeps its height. Underneath is a flat-profile rubber outsole scored in a grid — flat rather than lugged, because this is a shoe for indoors, shops and pavements rather than trails. The insole is 5 mm and removable. Uppers are coated canvas that wipes clean with a damp cloth, which is the honest way to keep a pale shoe looking reasonable.</p>
