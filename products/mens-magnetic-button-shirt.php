    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>An ordinary-looking cotton shirt that closes itself. Behind the placket there are eight pairs of neodymium magnets, each sewn into its own fabric pocket. You bring the two front edges roughly together at the hem, and they find each other and close up the line on their own. There is no hunting for a buttonhole and no fine pinching motion — which is the whole point, because buttons are usually the first thing to go. The buttons on the front are real buttons, stitched down over the magnet pockets. From the outside, and across a room, this is a shirt. Nobody has to know it fastens any differently, and that matters more to most people than any feature on this page. The cuffs use the same arrangement, so each sleeve closes with one hand — worth more than it sounds, since the second cuff is the hard one on any shirt. The cloth is a 3.6 oz cotton poplin, pre-washed so it does not shrink out of size on you, with a soft-roll collar that sits properly without plastic stays to lose. It is cut with a full chest and a straight hem so it can be worn out or tucked. Machine wash warm and tumble dry low with the magnets left in — they are enclosed and they stay put.</p>
      </div>
