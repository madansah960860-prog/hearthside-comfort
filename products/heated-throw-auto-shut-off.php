      <h2>About this item</h2>
      <div class="prose">
        <p>An electric throw for a chair, sized 50 by 60 inches — big enough to cover your lap and your feet, small enough not to trail on the floor. It runs on four heat settings from a single lit button on a hand controller, so there is no dial to read and no sequence to learn. Press it, the light moves along, and that is the setting. It turns itself off after three hours. That happens on every setting and every time, and it is not something you can switch off, which is the correct way round for a heated product. If you want it back on, press the button again. Inside, the heating element is a fine wire laid in a wide serpentine so it is spread rather than concentrated; the fleece is 280 gsm and thick enough that you cannot feel the wires through it. The cord is 9 feet, which is the difference between using it in your usual chair and not. To wash it, unplug the controller at the throw — it detaches completely — then machine wash warm on a gentle cycle and tumble dry low. Never wash it with the controller attached, and never dry clean it: solvents damage the wire insulation.</p>
