      <h2>About this item</h2>
      <div class="prose">
        <p>Loungewear that does not look like pyjamas. That distinction matters to a lot of people: this is the set you can be wearing when someone knocks. The top is a relaxed crew with a ribbed neckband and dropped shoulders; the trouser is a straight-leg pull-on with a wide waistband. Both pull on, and there is not a single button, zip or tie on either piece. The waistband is the part worth paying attention to. It is a 2 1/2-inch flat woven elastic, covered in the shell fabric and stitched at four points so it cannot twist inside its casing — and, more usefully, it is wide enough not to roll over on itself when you sit down, which is what a narrow band always eventually does. The fabric is a 9 oz cotton-blend French terry: smooth jersey on the outside, soft looped pile on the inside. It is warmer than jersey and lighter than fleece, and it softens with washing instead of pilling, which is the usual failure of a cheap lounge set. The top has a slightly longer back hem; the trouser has two deep side pockets set forward of the seam so they can be used while seated. Sold as a set in one size. Machine wash warm, tumble dry low.</p>
