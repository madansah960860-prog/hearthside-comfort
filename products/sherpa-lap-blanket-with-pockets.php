      <h2>About this item</h2>
      <div class="prose">
        <p>A lap blanket rather than a throw, and the difference is the size. At 40 by 55 inches it covers a lap, knees and feet while you are sitting, and it stops short of the floor — so it cannot trail, cannot be trodden on, and cannot catch under a chair caster or a walking frame. That is the whole reason a lap blanket exists as a separate thing. There are two pockets sewn into the front corners, nine inches deep, on the inside face. Hands are what get cold first when the rest of you is under a blanket, and the usual answer is to hold the edge closed, which means you cannot do anything else. With pockets your hands are covered and your arms are still free. It is made from two different fabrics laminated together: sherpa on one face — a deep curled pile that traps a lot of air — and micromink on the other, which is smooth and takes less time to warm up. Turn whichever you prefer towards you. Sherpa is warmer; micromink is better if a deep pile feels heavy. The edge is bound rather than hemmed, which keeps the two layers aligned through washing. Machine wash warm on a gentle cycle and tumble dry low; wash it by itself the first time, as sherpa sheds a little.</p>
