    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>Socks for wearing instead of slippers, around a house with hard floors. The grip is silicone printed in a fine grid across the entire underside — heel, arch and toe — rather than the single patch under the ball of the foot that most gripper socks use. The arch matters more than people expect, because it is the part that lands first coming down a step. The cuff is knitted non-binding: the elastic is looser and spread over a wider band, so the sock stays up without leaving a ring around the leg. It is a different construction from a normal ribbed cuff, not just a looser version of one. The heel has a proper Y-gore, which is the knitted equivalent of a shaped seam, and it is what stops the grip panel rotating under the arch over the course of a day. The blend is cotton-rich with a little nylon for shape and a trace of spandex, chosen so they are not slippery against a bare foot inside a shoe either. Three pairs to a pack, in two sizes. Machine wash warm and tumble dry low — but turn them inside out first, which keeps the silicone from dragging against the drum and lasting less well than it should.</p>
      </div>
