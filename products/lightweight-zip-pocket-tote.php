      <div class="prose">
        <p>A plain canvas tote with the two things most totes leave out: a zip across the top, and a base that lets it stand up. A bag that tips over and empties itself onto the floor of a car is the usual complaint, and both of those details fix it. The top zip runs the full width with a large flat pull. Inside, there is one zipped pocket on the back panel, sized for keys, a card and a phone, so the small things are not down at the bottom under the shopping. The base is a separate reinforced panel with a stiffener board sewn in, which is what makes the bag keep its shape and stand on its own. The handles are cotton webbing, stitched down the full height of the bag front and back rather than just tacked at the top — that is the seam that fails on a cheap tote. The drop is 10 inches, which is enough to go over a shoulder in a winter coat rather than only being carried in the hand. Empty, the whole thing weighs just over half a pound, and it holds about 22 pounds comfortably. The canvas is a 12 oz cotton that machine washes cold; wash it on its own the first time and let it air dry.</p>
