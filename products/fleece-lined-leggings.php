    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>Leggings with a brushed fleece interior — a warm layer for under a skirt, a dress or a loose trouser, or to wear on their own around the house. The face is a smooth knit so they look like ordinary leggings; the inside is brushed into a soft nap that holds a layer of warm air against the leg. The waistband is a wide flat band, not a drawstring and not a narrow elastic. It sits at the natural waist and is deliberately made from the same knit as the body rather than a separate elastic strip, so there is nothing to dig in and nothing to roll over when you sit. Getting them on is the usual leggings method — gather each leg down to the foot first, then feed the foot through — and there is enough stretch in the knit to do that seated. Seams are flatlocked throughout. On a close-fitting garment, a standard overlocked seam stands up as a ridge at the inner thigh and is the first thing to become uncomfortable after an hour. The knit is a polyester-spandex blend with good recovery, so they do not bag at the knee over a day's wear. Machine wash warm inside out and tumble dry low; washing them inside out is what keeps the brushed nap soft.</p>
      </div>
