      <h2>About this item</h2>
      <div class="prose">
        <p>The trouser most people in this store buy first. There is no button, no hook, no zip and no drawstring — the entire waistband is elastic, covered in the shell fabric, and it stretches about six inches past its relaxed measurement. You sit down, put both feet in, stand up and pull. That is the whole operation, and it can be done without looking. What stops it looking like an elasticated trouser is the front panel. The elastic is set into the back and sides only; across the front, the waistband is a flat faced panel, so there is no gathering where it shows. From the front this is a plain, flat-fronted trouser with a crease. From the back it does all the work. The cloth is a 7 oz polyester-viscose twill with a small proportion of elastane. It holds a crease without being pressed, sheds a crumb rather than holding it, and comes out of a tumble dryer ready to wear — which matters more than it sounds if ironing is difficult. Pockets are deep set-in side pockets, cut forward so they can be reached while seated, plus one buttoned back pocket. Inseam is a consistent 29 to 31 inches depending on size, and the hem is deep enough to be taken up by a tailor.</p>
