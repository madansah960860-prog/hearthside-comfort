    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A proper housecoat: the thing you put on over what you are already wearing, for the first hour of the day and the last. It closes with ten heavy-duty snaps rather than buttons. A snap closes by pressing — you can do it with the heel of your hand, or against your own body, and it does not require the pincer grip that a button needs. The snaps are the part that usually fails on a garment like this, so they are ring-spring snaps set through a double layer of reinforced placket rather than prong snaps punched through single cloth. Prong snaps tear out; these do not. They are also spaced closer together at the bust than at the hem, where gaping actually happens. The fabric is a 5 oz brushed cotton — warm to the touch straight out of the wardrobe, which is the point of a housecoat in the morning. Sleeves are three-quarter length so they stay clear of a sink or a bowl. There are two large patch pockets set forward of the side seam, so they can be reached while sitting rather than only while standing, and they are bar-tacked at the corners because pockets are what people pull on. Machine wash warm, tumble dry low.</p>
      </div>
    </section>

