    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A traditional moccasin, cut lower at the back than most so you can step in without hooking a finger behind your heel. The apron seam across the toe is stitched rather than moulded, which is what gives a moccasin its give — the upper relaxes over the first week and settles around the shape of your foot instead of pressing on it. The footbed is 15 mm of viscoelastic memory foam over a firmer base layer. Memory foam on its own bottoms out; the base layer is there so the slipper still has structure after a few months of being stepped into every morning. Above it sits a faux-shearling lining that continues under the arch and up the sides, so there is no cold patch where the foot meets the seam. The outsole is a textured rubber unit bonded to the upper across its whole surface, not stitched round the edge. That matters on carpet, where a stitched welt is the thing that catches. It comes in whole sizes 6 through 12 in a single D width. Wash it cold inside a laundry bag and dry it flat — tumble drying will cook the memory foam and it will not come back.</p>
      </div>
    </section>

