      <div class="prose">
        <p>A skort is a skirt with a short built into it, and it solves a specific everyday problem: a skirt that rides up when you shift in a chair or get out of a car. The outer layer here is a knee-length knit skirt with a soft unpressed pleat at the front; the inner layer is a plain jersey short, attached at the waistband only, so the two move independently and the outer skirt still hangs like a skirt. The waistband is fully elastic with no button, no zip and no drawstring — a two-inch covered band with the same woven elastic used in our pull-on trouser, so it recovers rather than going slack. Pull it on standing or seated; there is nothing to fasten afterwards. The fabric is a 9 oz ponte knit, which is the right cloth for this garment: it is stable enough to hold a pleat and a hem without lining, it does not crease when you sit on it, and it recovers its shape at the back of the skirt. Lighter knits bag out behind the knee within an hour of sitting. There is one hidden pocket in the right side seam of the inner short, deep enough for a key and a card. Machine wash warm, tumble dry low, no pressing.</p>
