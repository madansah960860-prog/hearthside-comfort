        <summary>How do I get them on without a struggle?</summary>
        <p>Turn the sock inside out as far as the heel, place the heel first, then roll the leg upward in stages. Do not pull from the top band — that is what stretches them out and eventually tears them.</p>
      </details>
      <details>
        <summary>How long do they keep their compression?</summary>
        <p>Elastane relaxes with wear and washing. Most people replace compression socks every three to six months of regular use. Air drying makes them last noticeably longer.</p>
