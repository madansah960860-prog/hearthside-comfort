        <summary>What does 15–20 mmHg mean?</summary>
        <p>It is the compression class — the pressure the knit applies, measured at the ankle, in millimetres of mercury. It is stated here so you can match it to what you have been advised to wear. We do not advise a class ourselves.</p>
