      <div class="prose">
        <p>A knee-high sock knitted to a graduated 15–20 mmHg profile: the knit is firmest around the ankle and eases as it goes up the calf. That figure is the compression class, and it is printed on the packaging so you can check it against whatever you have been told to wear. <strong>Ask your doctor before using compression socks, especially if you have diabetes, circulation problems, or any condition affecting the skin of your legs or feet.</strong> We describe what this sock physically is — a knitted graduated compression garment in a stated class — and we make no claim about what wearing it will do for you. That is a conversation for you and a clinician, not for a product page. Practically: getting a compression sock on is the hard part, so this one has a reinforced heel pocket that holds its shape while you position it. Turn the sock inside out down to the heel, set the heel square, then roll the leg up in stages rather than hauling on the top band — pulling from the top is what tears them. The top band is wide and flat so it does not dig in behind the knee. Two pairs to a pack in three sizes, sized by shoe size and calf circumference together. Wash them warm and air dry; a hot dryer takes the life out of the elastane and the compression class with it.</p>
