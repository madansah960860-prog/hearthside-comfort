    <section class="band">
      <h2>What it does</h2>
      <ul class="whatitdoes">
        <li>The instep strap opens all the way flat, so the foot goes in without being forced past a fixed opening.</li>
        <li>Hook-and-loop closure adjusts across about 1 1/2 inches, which takes up or releases room as the foot changes through the day.</li>
        <li>A 1-inch fabric heel tab gives you something to pull on so you are not reaching down past your ankle.</li>
        <li>The rubber outsole is scored in a grid and runs the full length of the slipper, including under the heel.</li>
        <li>Machine washable on a cold, gentle cycle.</li>
      </ul>
    </section>

    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>This is the slipper for the part of the day when shoes are too much and bare feet are not enough. The whole upper folds open along the instep, so you are not pushing your foot through a closed slot — you lay it in, pull the heel tab, and press the strap flat. The hook-and-loop patch is cut long on purpose: about an inch and a half of adjustment, which is enough to take up slack in the morning and let the strap out again by evening, when feet are usually a little larger. Inside, there is a 12 mm foam footbed under a brushed knit lining that does not feel cold on a bare foot in January. The footbed is contoured slightly at the arch and flat at the toes, so it does not fight a wide forefoot. The outsole is real rubber rather than a printed dot pattern, scored in a grid, and it wraps the heel as well as the ball of the foot — the two places people actually slip on a kitchen floor. It comes in D and EE widths, both in whole sizes 6 through 12. Wash it cold on a gentle cycle and let it air dry; the strap holds its grip through washing because the hook patch is stitched down at its edges, not glued.</p>
      </div>
    </section>

