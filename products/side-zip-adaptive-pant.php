    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A trouser that opens completely flat. The zips run the full length of both outside seams, from the hem right up to the waistband, so the garment can be laid open like a blanket, positioned, and then closed around the legs. For anyone dressing while seated, dressing someone else, or working around a cast, a brace or limited hip movement, that changes the job entirely — nothing has to be threaded over a foot and pulled up a leg. Both sliders carry a 1-inch ring pull, and both zips close from the bottom upward, which is the direction that needs less shoulder movement. The teeth are a No. 5 moulded chain, chosen because coarser teeth tolerate being closed over fabric bulk without splitting. The waistband is elastic across the back and flat across the front, the same arrangement as our pull-on trouser, so the fit is familiar and the front still looks plain. The cloth is a 8 oz cotton-blend twill with a denim look and a softer hand than real denim, which matters for anyone sitting in it for long periods — stiff denim at the back of the knee is uncomfortable within an hour. Pockets are set into the front only; there are no back pockets, because a back pocket under a seated person is a pressure point.</p>
      </div>
    </section>

