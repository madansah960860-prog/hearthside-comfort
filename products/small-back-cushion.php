    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>Most armchairs and sofas are too deep, which leaves a gap behind the small of your back and means you end up perched forward or slumped. This is a small cushion made to fill that gap: 16 inches wide, 12 tall, and about five inches deep when it is plumped. It is deliberately soft rather than firm. A rigid moulded support has to be in exactly the right place to be comfortable, and if it is not, it is worse than nothing. A cluster-fibre cushion squashes into whatever shape the gap actually is, and it can be pushed up or down in a second without unstrapping anything. The filling is a down-alternative polyester cluster — short curled fibres spun into small balls, which move against each other the way down does and recover afterwards instead of staying flat. There are no feathers in it. The zip is hidden in the bottom seam, because a visible zip is a hard edge in exactly the spot you lean on. The cover is a soft woven cotton blend and unzips completely; both the cover and the insert can be machine washed. As with everything in this department, we are describing the object — its size, its filling, its shape — and making no claim about posture, backs or anything medical.</p>
