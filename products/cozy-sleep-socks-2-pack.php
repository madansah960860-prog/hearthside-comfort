      <h2>About this item</h2>
      <div class="prose">
        <p>Socks for bed, which is a different job from socks for walking. Everything here is loosened: the cuff is wide and only lightly elasticated, the leg is knitted at a slack gauge, and the foot is cut generously. A sock that holds on properly all day is exactly the wrong thing to sleep in, because it leaves a mark and because you never take it off in the night when your feet get warm. There is no silicone grip on the sole, and that is on purpose. Grip is excellent on a kitchen floor and a nuisance in a bed, where it catches on the sheet every time you move your foot. If you want grip for walking about, the Non-Slip Gripper Socks are the ones to buy. The inside is brushed, so they feel warm as soon as they go on rather than after ten minutes — which is the entire point of putting socks on at bedtime. The yarn is an acrylic-nylon blend with a little wool, chosen over pure wool because it survives a tumble dryer and because it does not itch against a bare foot at night. One size covers U.S. 6 through 12 thanks to the slack gauge. Two pairs per pack. Machine wash warm, tumble dry low.</p>
