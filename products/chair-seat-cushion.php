    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A plain square cushion for a chair you already own and already like, but which is too hard to sit in for an hour. It is 17 inches square and three inches thick — enough to make a wooden dining chair comfortable without raising you so far that the table is at the wrong height. The core is a single piece of high-resilience foam rather than memory foam. That is a deliberate choice for a seat: memory foam softens under steady pressure and gradually bottoms out over a long sit, while high-resilience foam keeps pushing back. It also recovers its shape immediately when you stand, so the cushion does not hold a dent. There are two fabric ties at the back corners. Tie them round the chair uprights and the cushion stops creeping forward, which is the usual annoyance with a loose seat pad — and the reason people end up sitting half on and half off one. Underneath there is a rubberised non-slip backing for chairs with no uprights to tie to. The cover is a woven cotton blend, unzips along three sides, and machine washes cold. The foam itself must not be washed; spot clean it and let it air. We describe this cushion by its size, its foam and its fixings only — it is a seat cushion, not a medical device, and we make no claim about what it will do for anyone.</p>
