      <div class="prose">
        <p>A 12-pound weighted blanket, 48 by 72 inches. Weighted blankets are sized by body weight rather than bed size, and the usual guide is about ten per cent of your own weight — so 12 pounds suits an adult of roughly 110 to 140 pounds. It is deliberately cut to cover a person rather than a mattress; a weighted blanket that hangs over the sides drags itself onto the floor. <strong>Please read this before buying.</strong> A weighted blanket should not be used by anyone who cannot reliably remove it without help, and it must never be used on a child or an infant. If you have a breathing or circulatory condition, or any difficulty moving in bed, ask your doctor before using one. We describe the object — its weight, its fill and its construction — and we make no claim about sleep, anxiety, or any condition. The fill is glass microbeads mixed with a thin polyester batting. Glass beads are much smaller and denser than the plastic pellets used in cheaper blankets, so the blanket is thinner, cooler and far quieter when you move. The pocket grid is four-inch squares, each double-stitched, which keeps the weight even instead of letting it pool. Machine wash warm in a large machine — 12 pounds wet will overload a small drum — and tumble dry low.</p>
