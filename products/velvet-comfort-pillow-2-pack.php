      <h2>About this item</h2>
      <div class="prose">
        <p>Two soft square pillows, 18 inches each, for the jobs the firm cushions in this department are wrong for. A firm foam cushion holds a position; these do the opposite — they squash into whatever gap you put them in and stay there. Behind the small of your back in an armchair, under an elbow, beside you to lean against, or propped behind your shoulder in bed. The fill is a down-alternative polyester cluster: short curled fibres spun into small clusters rather than a flat fibre batt. Clusters move against each other the way down does, which is why the pillow can be moulded and will recover afterwards instead of staying dented. There are no feathers in it at all, which matters if feathers cause you trouble. The covers are a short-pile polyester velvet with a hidden zip set into the bottom seam — hidden because a visible zip is a hard edge in exactly the place you lean on. Both the cover and the insert can be machine washed, which is unusual; wash the inserts on a gentle cycle and tumble dry them low with a couple of dryer balls to break the clusters back up. Sold as a pair, because one of these is rarely enough.</p>
