      <div class="prose">
        <p>Two covers for cushion pads you already have. This is the cheapest way to make a tired chair look cared for again, and it is far less wasteful than throwing out perfectly good cushions because the covers have gone grey. They fit standard 18-inch square pads. The fabric is a heavy textured cotton blend with a visible woven structure. Weight matters in a cushion cover: a thin one shows every lump of the pad inside and sags between the corners, while a heavy weave holds a square shape and hangs properly. It is a plain, quiet texture rather than a pattern, so it does not fight with whatever else is in the room. The zip is hidden in the bottom seam. On a cushion you actually lean against, an exposed zip is a hard ridge in the wrong place, and it is worth the extra seam to hide it. The covers are cut about half an inch generous so that a plump pad reaches into all four corners — an undersized cover is why so many cushions end up looking pinched. Machine wash them cold on a gentle cycle and tumble dry low. Close the zip before washing so it does not catch on anything else in the drum.</p>
