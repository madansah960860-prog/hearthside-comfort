    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>The simplest garment in the store, and deliberately so. There is nothing to fasten: a wide scooped neck, short set-in sleeves and a body cut full from the bust down. It goes on over the head in one movement and there is nothing to check afterwards. The two things that make a nightgown uncomfortable are a narrow hem and a clinging fabric, and both are about turning over in the night. This one is cut with an A-line body that measures 58 inches around the hem at size L, so there is nothing to bind the legs, and there is a 7-inch vent at each side seam so getting in and out of bed does not mean gathering the skirt. The fabric is a 5.5 oz cotton-modal jersey. Modal is a viscose made from beech, and blending it with cotton does two useful things: it makes the jersey drape instead of standing away from the body, and it stops the fabric sticking to skin the way pure cotton does when you are warm. The neck and armholes are finished with a self-fabric binding rather than elastic, so nothing grips. Mid-calf length. Machine wash warm and tumble dry low; it needs no ironing.</p>
      </div>
