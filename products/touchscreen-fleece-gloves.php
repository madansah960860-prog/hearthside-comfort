      <div class="prose">
        <p>Fleece gloves with conductive thread knitted into the thumb and the first two fingertips of both hands — both hands, not just the right, which is worth checking on any pair you buy. The thread is knitted through the fabric rather than printed on the surface, so it keeps working after washing and after the fingertips have worn a little. The point is not really the phone. It is that you stop taking your gloves off and putting them down, which is how gloves get lost and how hands get cold at the exact moment you are standing still outside fiddling with something. Across the palm and the inside of the fingers there is a pattern of silicone dots. On a fleece glove that matters for a handrail, a walking stick, a car door and a hot cup — plain fleece is slippery, particularly when it is slightly damp. The cuff is a 2 1/2-inch rib that stays put under a coat sleeve instead of riding up and leaving a cold gap at the wrist. The shell is a 260 gsm polyester fleece with a brushed lining. Two sizes, fitted by palm circumference rather than by hand length, which is the measurement that actually decides whether a glove fits. Machine wash cool and air dry.</p>
