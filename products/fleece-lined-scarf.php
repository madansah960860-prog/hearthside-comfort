      <h2>About this item</h2>
      <div class="prose">
        <p>A knitted scarf with a fleece lining stitched to the back. A single-layer knit scarf looks the part and is mostly holes — the wind goes straight through it, and the side against your neck is the scratchy side. Backing it with fleece fixes both problems at once: it blocks the wind and puts a smooth warm surface against the skin. It is 70 inches long and 11 inches wide, which is the length that lets you loop it once around the neck and pass both ends through, and still have enough left to tuck into a coat. A 60-inch scarf will not do that, which is why so many scarves end up just hanging. The ends are finished flat and stitched closed, with no fringe. Fringes catch in car doors, zips and wheels, and they are the first part of a scarf to look tired. The knit face is an acrylic with enough body to hold its shape; the lining is a light polyester fleece, and the two are stitched together along both long edges so the layers cannot shift and bag. Machine wash cool on a gentle cycle and dry flat — hanging a wet lined scarf will stretch the knit face away from the lining.</p>
      </div>
