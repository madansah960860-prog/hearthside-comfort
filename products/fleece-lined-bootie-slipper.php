    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A bootie rather than a scuff, for people whose feet get cold at the ankle first. The cuff comes up about four inches above the ankle bone and can be worn up, for warmth, or folded down, which shortens it and makes it easier to get past the heel. The opening itself is not elasticated. That is deliberate — an elastic cuff is the thing that makes a bootie a struggle, and the shape here holds by cut instead. Inside it is lined edge to edge in a 260 gsm polyester fleece, including up the inside of the cuff, so there is no bare seam against the ankle. The outer shell is the same fleece brushed on the outside, which is why it packs down soft rather than standing up stiff. The sole is a rubber dot grid printed across the entire footprint, heel to toe, bonded to a 8 mm foam layer. It is a house sole, not an outdoor one: it will grip a wood or tile floor and it will wear through quickly on concrete. Sizes run S to XL rather than numerically, which is the honest way to size a soft bootie — each size covers roughly two U.S. shoe sizes. Machine wash cold and air dry.</p>
      </div>
    </section>

