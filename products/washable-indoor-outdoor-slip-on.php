      <h2>About this item</h2>
      <div class="prose">
        <p>The shoe that lives by the back door. It is made to be stepped into while standing — the collar is reinforced so it holds its opening rather than collapsing when you put your foot on it, and the heel is cut at an angle that guides the foot down and in. For a trip to the bin, the post or the car, that is the difference between putting shoes on and not bothering. Because a door shoe gets dirty, this one washes. The upper is a coated knit that sheds a light shower, the lining is a quick-drying mesh, and the sole is bonded rather than glued at the welt — the three things that usually stop a shoe surviving a machine. Wash it cold on a gentle cycle and leave it to air dry overnight; do not put it in the dryer. The outsole is siped: the rubber is cut with dozens of fine slits that open under load and grip a wet step, which is a genuinely different thing from a deep tread. Deep lugs shed mud; sipes hold on wet smooth surfaces, which is what a doorstep and a driveway actually are. It is cut on an EE last throughout, so it goes on over a thick sock without squeezing, and in whole sizes 6 through 12.</p>
