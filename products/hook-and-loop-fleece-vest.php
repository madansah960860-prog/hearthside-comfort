    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A sleeveless fleece that closes with a continuous hook-and-loop front rather than a zip. The loop side runs the full height and width of the right front panel, and the hook side runs up the left edge, so the two overlap and hold anywhere across about three inches of range. There is nothing to start, nothing to align, and it can be fastened with a closed fist. A vest is the right garment for this closure because there are no sleeves to get an arm down — you put it on the way you would a waistcoat, one shoulder at a time, and the whole front is then reachable. It also means the fit adjusts across the chest without changing size, in the same way the wrap top does. The fabric is a 280 gsm anti-pill polyester fleece, double-faced so the inside is as soft as the outside. Anti-pill matters on a garment that will rub against a chair back for hours. The armholes are bound rather than elasticated, so nothing grips the upper arm, and the hem sits at high hip. Both hand pockets are zipped, with the same 1-inch ring pulls used on our cardigan. Machine wash warm with the front closed — an open hook panel will collect lint from everything else in the drum.</p>
      </div>
