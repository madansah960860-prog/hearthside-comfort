    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>The lightest thing in this department, and the one people put on first in the morning. The upper is knitted as a single piece with no seams and no separate collar, so the opening is not a fixed hole — it stretches as your foot arrives and closes around it afterwards. There is nothing to undo, nothing to adjust, and nothing that has to be held open with a hand. The knit is deliberately looser across the forefoot than around the heel. That is where the give is needed: a wide forefoot, a bunion or a hammer toe presses against the side of a conventional slipper, and this simply moves out of the way. Around the heel the knit is tighter, which is what keeps the shoe on without a back strap. The sole is thin on purpose — 8 mm of foam with silicone grip printed across the full underside. A thin sole keeps you closer to the floor and makes it easier to feel where your feet are, which many people prefer indoors to a thick cushioned slipper. It rolls up small enough to pack. Machine wash cold, air dry, and it will be ready by morning. Sizes run S to XL, each covering about two U.S. shoe sizes.</p>
      </div>
