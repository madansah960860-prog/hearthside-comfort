    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A walking shoe that opens wide and closes with two straps. The tongue is gusseted only at the bottom, so the whole upper falls open when both straps are released — you step in from above rather than threading your foot into a tunnel. Then one strap over the forefoot, one at the ankle, pressed down in that order, and you are done. There are no laces to tie, and nothing to come undone halfway round the block. The last is cut genuinely wide, not a standard last with a stretchy panel over the toes. At size 10 in EE the forefoot measures 4 3/8 inches across inside, and the toe box keeps its height right to the end, so the little toe is not pressed inward. The heel counter is firm and holds its shape, which is what keeps a wide shoe from feeling sloppy. Underfoot there is a 22 mm compression-moulded midsole and a rubber outsole with a 4 mm lug pattern, cut deeper under the heel where most of the wear happens. The insole lifts out in one piece, so if you already wear an insert you can swap it straight in without losing depth. Uppers are breathable mesh with synthetic overlays at the strap anchors, where the pull is.</p>
      </div>
    </section>

