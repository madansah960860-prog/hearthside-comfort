    <section class="band">
      <h2>Common questions</h2>
      <p>These are our answers, written by the people who run this store. They
      are not customer reviews and they are not quotes from anyone else.</p>
      <details>
        <summary>Are these the same as a shoe marked wide by a regular brand?</summary>
        <p>No. A shoe marked wide is often a standard last with a roomier upper. This one is built on a wide last, so the sole itself is broader and the footbed is wider under the ball of the foot.</p>
      </details>
      <details>
        <summary>Can I take the insole out to fit my own?</summary>
        <p>Yes. It lifts out in one piece. Doing so gains you about 5 mm of depth.</p>
      </details>
      <details>
        <summary>Do the straps loosen as you walk?</summary>
        <p>They should not. Both straps anchor through a synthetic overlay rather than into mesh, which is what usually causes creep. If a strap does loosen, the shoe is a size too large.</p>
      </details>
    </section>

