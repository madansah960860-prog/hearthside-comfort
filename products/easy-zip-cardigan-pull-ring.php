    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A cardigan with the fastening problem solved at both ends. Starting a zip is the genuinely hard part — lining up a small pin with a small box while holding both sides of a garment together. Here the box at the hem is moulded wide and stays open on its own, so the pin only has to be dropped in rather than threaded. Then there is a 1 1/4-inch flat metal ring on the slider: big enough to put a whole finger through and pull, rather than pinching a tab. The zip itself is a chunky No. 5 with moulded teeth. Larger teeth engage more forgivingly than fine ones and are far less likely to jam halfway, which on a cardigan usually means the garment comes back off again. The knit is a 12-gauge cotton-acrylic in a flat jersey stitch, substantial enough to sit properly on the shoulder without being heavy on the arms. It is machine washable and it does not need blocking — it comes out of the wash the shape it went in, which is not true of most natural-fibre cardigans. Pockets are set-in patches at hip height, deep enough that a phone does not tip out when you sit down. Sizes S through 3X, cut with a straight body rather than a waist shape.</p>
      </div>
    </section>

