      <div class="prose">
        <p>A compact umbrella that opens itself at the press of a button. Opening a manual folding umbrella takes two hands and a push — one hand on the handle, one running the canopy up the shaft — which is awkward when the other hand is holding a stick, a bag or a car door. This one needs one thumb. It is deliberately auto-open only, not auto-close. Automatic closing mechanisms snap the ribs shut with real force and are the single most common way people catch their fingers in an umbrella. Closing this one is a deliberate two-handed action, which is safer and also much less likely to break. The canopy is 42 inches across when open — big enough to keep your shoulders dry, where a 36-inch pocket umbrella only really covers your head. The eight ribs are fibreglass rather than steel, so they bend a long way in a gust and spring back rather than taking a permanent kink. The handle is rubberised and 4 1/2 inches long, which is enough for a whole hand rather than three fingers, and it has a wrist strap. Folded, it is 11 inches and comes with a sleeve. Let it dry open before putting it away.</p>
