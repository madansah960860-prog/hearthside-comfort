    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A wrap top, which is the oldest easy-on garment there is and still one of the best. There is no placket, no row of fastenings and nothing to line up. You put one arm in, bring the front panel across your body, and tie a single ribbon at the side seam. That is the entire closure, and it can be done without looking down. Because it wraps rather than buttons, the fit adjusts by several inches without changing size. On a day when a fixed garment would feel tight, the wrap simply crosses less far. That makes it one of the few tops that stays comfortable across a fluctuating waistline, and it is the reason we put it in the adaptive department rather than filing it as a plain knit top. The fabric is a 6 oz viscose-elastane jersey with a heavy, fluid drape. Light jersey clings and shows every fastening beneath; this weight hangs away from the body and holds the wrap line properly. The inner panel is secured with a hidden ribbon through an eyelet at the opposite side seam, so the top does not swing open when you move. Sleeves are three-quarter with a loose cuff. Machine wash cool, hang to dry, no ironing.</p>
      </div>
