    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A memory foam neck pillow for a car, a train, a plane or an armchair. The shape is a horseshoe with a deliberately raised back panel — most of the work a neck pillow does is at the sides, stopping your head tipping sideways when you doze, but if the back is thin your head also tips backwards, which is why so many of them are uncomfortable. The two ends are joined at the front with a small side-release clip. Without one, the ends push apart as soon as your chin drops and the pillow slides round your neck. The clip is on a short adjustable strap so it can be loosened to sit comfortably rather than pulling the ends together tightly. The foam is a medium-density memory foam that softens with body heat. The neck opening is 4 1/2 inches, which suits most adults; the outer width is 12 inches. It comes with a compression carry bag that squeezes it down to about 7 by 5 inches and clips to a bag handle, and the pillow recovers its shape within a minute or two of coming out. The cover is a soft velour, unzips completely and machine washes cold. Do not wash the foam.</p>
      </div>
