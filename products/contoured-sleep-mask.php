      <h2>About this item</h2>
      <div class="prose">
        <p>A contoured mask rather than a flat one. Flat masks press directly on the eyelids, which most people find uncomfortable within about twenty minutes and which makes it impossible to open your eyes without lifting the mask. This one is moulded with two eye cups that stand about three quarters of an inch clear, so nothing touches the eye at all and you can blink or open your eyes freely inside it. The part that actually decides whether a mask works is the nose. Light comes in under the bridge on almost every flat mask, and no amount of strap tension fixes it. Here the bridge is contoured and fitted with a soft flexible insert that follows the shape of your nose and closes the gap without pinching. The strap is a flat hook-and-loop band adjusting between 18 and 26 inches — adjustable anywhere in that range rather than in fixed steps, and easy to set with one hand. It lies flat at the back of the head rather than using a buckle, so there is nothing hard to lie on. The outer cover is a brushed polyester that unzips and goes in the machine; the moulded shell does not. Wash the cover cold and let it air dry.</p>
      </div>
