      <h2>About this item</h2>
      <div class="prose">
        <p>A plain cotton undershirt that opens at both shoulders. Three snaps on each side release the front panel from the back, so the shirt can be laid on and closed rather than pulled over the head. Raising both arms above the head is the movement that stops a lot of people dressing themselves, and an undershirt is the layer where that is easiest to design around. Everything about the construction is about what sits against skin. The seams are flatlocked, so the join lies flush instead of standing up as a ridge; the snaps are low-profile and capped on the underside, so the metal does not touch you; and there is no printed label, only a heat-transferred size mark inside the back neck. The cloth is a 4.3 oz combed ring-spun cotton jersey, pre-shrunk. Combed cotton costs more than carded and is worth it here — the short fibres are removed, so the surface stays smooth rather than pilling where a garment rubs. The body is cut straight and slightly long so it stays tucked. Two shirts per pack. Machine wash warm and tumble dry low with the snaps closed, which stops them catching on anything else in the drum.</p>
