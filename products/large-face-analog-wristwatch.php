    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A watch designed around one thing: being readable at arm's length without glasses. The dial is 1 5/8 inches across with a plain matt white face and black Arabic numerals a quarter of an inch tall. All twelve numbers are printed — not four numbers and eight bars — because the moment a dial asks you to count round to work out where the hand is pointing, it has failed. The hands are black, tapered and clearly different lengths, with a thin red second hand so it is obvious at a glance that the watch is running. The crystal is mineral glass rather than acrylic. Acrylic is cheaper and scratches into a haze within a year, which defeats the point of a large clear dial. The movement is a quartz movement, so there is no winding and no setting beyond the crown; the battery is a standard cell any jeweller can change. The strap is a soft padded leather, adjusting from 6 to 8 1/2 inches, with a tail cut long and a fixed keeper — small details that make the difference between fastening a watch easily and fumbling with it. Water resistance is 3 ATM: splashes and handwashing are fine, swimming and showering are not.</p>
      </div>
    </section>

