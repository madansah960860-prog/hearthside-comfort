      <h2>About this item</h2>
      <div class="prose">
        <p>A plain knitted beanie with a deep cuff. Most of what makes a hat work is the cuff: three inches folded, which is enough to cover the tops of the ears rather than sitting on them. A shallow cuff looks neater and leaves the ears cold, which is the only part of this that most people actually notice in February. It is knitted in a soft 2x2 rib, which stretches comfortably across 21 to 24 inches of head circumference — that covers most adults without needing sizes. The rib means it holds on in wind without gripping, and it recovers its shape rather than gradually growing. Across the forehead band there is a knitted lining, doubled through the cuff. A single layer of knit lets wind straight through at exactly the point where you feel it most, and doubling that band is the cheapest real improvement you can make to a hat. There is no pom-pom, deliberately: a pom-pom makes a hat impossible to wear against a car headrest or an armchair back. The yarn is an acrylic-wool blend that machine washes cool and dries flat overnight.</p>
