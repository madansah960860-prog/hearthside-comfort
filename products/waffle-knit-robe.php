    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>The robe for a warm house, a summer morning, or straight out of the bath. Waffle weave is a honeycomb structure that traps a layer of air without using much yarn — so the cloth is light in the hand and on the shoulders, but not cold. It is the opposite proposition to our fleece robe, and most people who own both reach for this one nine months of the year. It is also the one to have if you put a robe on while still damp. Waffle cotton has a large surface area and a loose structure, so it takes up water quickly and then dries quickly rather than staying heavy. A fleece robe in the same situation stays wet for hours. The cloth is a 240 gsm cotton waffle, pre-washed, which is why it arrives soft rather than stiff. It softens further over the first month and then stays that way. Construction is plain and sturdy: a shawl collar, three-quarter-length turn-back cuffs, two patch pockets, and a self belt through two stitched loops so it stays with the robe. There is a hanging loop at the back neck, which sounds trivial and is the reason a robe ends up on a hook rather than on a chair. Machine wash warm, tumble dry low.</p>
      </div>
