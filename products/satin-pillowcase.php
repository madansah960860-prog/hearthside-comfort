    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A satin pillowcase is one of the cheapest changes you can make to a bed, and the difference is purely mechanical: cotton has a textured surface that grips skin and hair, and satin does not. If you turn over a lot in the night, or if you wake with your hair in a state, a smooth surface is simply less work. This one is woven from polyester satin rather than knitted, so it has a proper dense drape and the sheen does not wash out. The closure is an envelope — an 8-inch internal flap that the pillow tucks behind. There is no zip, which matters twice over: nothing to find and operate in the dark, and nothing hard near your face. The seams are French seams, which means the raw edges are enclosed inside a second seam rather than overlocked. It costs more to make and it is the reason no cut edge ever ends up against your cheek. The case is cut generously so the pillow is not compressed at the corners, and it comes in standard and queen. Machine wash cold on a gentle cycle and tumble dry low or hang — satin does not tolerate a hot dryer, and a hot iron will glaze it.</p>
