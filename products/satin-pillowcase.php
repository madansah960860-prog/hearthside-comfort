      <details>
        <summary>Is this silk?</summary>
        <p>No. It is woven polyester satin. Satin is a weave, not a fibre — we say so plainly because a lot of listings blur the two. Silk costs several times as much.</p>
      </details>
      <details>
        <summary>Will it slide off the bed?</summary>
        <p>The case will not slide on the pillow, because it is an envelope. A satin pillow can slide on a satin sheet; on a cotton sheet it stays put.</p>
      </details>
      <details>
        <summary>Does the sheen wash out?</summary>
        <p>Not if you keep it off a hot wash and a hot iron. The sheen comes from the weave, but heat flattens the filament and dulls it permanently.</p>
      </details>
