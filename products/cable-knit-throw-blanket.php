      <h2>About this item</h2>
      <div class="prose">
        <p>A proper cable-knit throw, 50 by 60 inches, in an acrylic-cotton blend. The cables are knitted rather than pressed or printed, so the stitch has real depth and the throw has the weight and the drape that goes with it — about three and a half pounds, which is enough to stay over your shoulders when you lean forward for your cup. The blend is the reason it can be machine washed. A wool cable throw has to be hand washed and dried flat, which in practice means it gets washed twice a year. This one goes in the machine on a warm gentle cycle and comes out the same shape, because acrylic does not felt and the cotton content keeps it from feeling plasticky. It also does not itch, which rules out wool for a lot of people before anything else. All four edges are whipstitched by hand — a close overcast stitch round the edge rather than a machined hem. On a chunky knit that is what stops the ends working loose over years of being pulled off the back of a chair. There is no fringe, deliberately: a fringe on a throw catches on chair arms, buttons and wheels. Machine wash warm, tumble dry low, and shake it out before you put it away.</p>
      </div>
