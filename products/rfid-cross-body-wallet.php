      <h2>About this item</h2>
      <div class="prose">
        <p>A small cross-body bag that works as a wallet. The advantage over a wallet in a pocket or a handbag is simple: it goes over your head and stays on your body, so it cannot be left on a counter, and it can be opened with one hand while it is still being worn. The card section is lined with an RFID-blocking layer. That is a metallised fabric that interferes with the radio field a contactless reader uses, so a reader held against the outside of the bag cannot wake the cards inside. We will describe it as exactly that, and note that opinions differ on how large a real-world risk contactless skimming is — the lining is there, it does what it does, and we are not going to frighten anyone into buying it. There are eight card slots, a slip pocket for notes, and a separate zipped coin pocket on the back panel so coins are not loose among the cards. The main zip has a large flat pull tab, which is easier to find and hold than a small metal tag. The strap adjusts between 42 and 54 inches through a slider, and both ends clip off entirely if you would rather use it as a clutch. The body is a coated textured leather that wipes clean.</p>
