    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A plain canvas slip-on, cut wide, with the two things that make a slip-on workable: elastic that actually opens, and something to pull on. The gores on both sides are 1 3/4 inches of knitted elastic rather than the narrow strips usually used, so the collar opens properly instead of resisting all the way. At the back there is a stitched webbing loop — small, flat, and strong enough to take a proper pull. The upper is 10 oz cotton canvas over a soft twill lining, which is why it washes. Run it cold on a gentle cycle and air dry it; the vulcanised sole is bonded around the full perimeter and takes water without lifting. Canvas will fade a little over several washes, evenly, which most people prefer to a coated shoe that goes patchy. The sole is vulcanised rubber with a scored grid and a low 14 mm profile. That gives a flat, stable stance and good contact on indoor floors and dry pavement — this is a shoe for the shops and the garden path rather than for hills. The insole is a removable 5 mm cushion. Both D and EE widths run the full size range, and the toe box is shaped rather than tapered, so the little toe is not pushed in.</p>
      </div>
    </section>

