      <div class="prose">
        <p>A shawl is the most forgiving warm layer there is. It goes over whatever you already have on, it needs no sleeves threaded and no fastening, and it comes straight off again when you get warm. For anyone who finds a cardigan awkward at the shoulder, this does the same job with none of the movement. At 78 by 28 inches it is large enough to be useful. A lot of what gets sold as a shawl is really a wide scarf and slides off the shoulders within a minute; this one has enough width to cover both shoulders and the upper arms, and enough length to cross at the front and still stay put without a pin. The border is ribbed on all four sides. A plain stocking-stitch edge curls inward — it is a property of the stitch, not a fault — and a rib is the standard way to stop it. It also gives the edges enough weight to hang properly. The yarn is an acrylic-wool blend at a light gauge, so it is warm without being hot indoors, and it machine washes on a cool gentle cycle. Dry it flat rather than on a hanger; something this size will stretch under its own weight when wet.</p>
