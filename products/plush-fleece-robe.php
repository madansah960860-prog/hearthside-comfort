    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>The heaviest robe in the store, and the one for a cold house in the morning. The fabric is a 380 gsm coral fleece with a long pile on the face and a smooth knit back, which is why it feels warm immediately rather than needing a minute to warm up. Fleece at this weight has a habit of matting after a few washes; this one is finished to resist that, so the pile stays open rather than going flat and shiny. The collar is a full shawl — a single wide band of fleece that runs from the hem up round the neck and down again. It holds warmth at the throat without needing a button, and it sits flat rather than standing up against the neck. The belt is a genuine problem on most robes, because it disappears in the wash; this one runs through two firmly stitched loops at the side seams so it stays with the garment. There is also an inner tie, which holds the left panel closed on its own — useful if tying a belt is awkward, because the robe then stays decent with just the inner tie done. Pockets are large patch pockets set forward of the side seam so a seated person can reach into them. The hem falls just below the knee. Machine wash warm on its own — fleece sheds lint onto everything else — and tumble dry low.</p>
      </div>
