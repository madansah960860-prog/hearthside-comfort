    <section class="band">
      <h2>About this item</h2>
      <div class="prose">
        <p>A rain boot sized and shaped around the actual difficulty, which is not keeping water out — any rubber boot does that — but getting the thing on and off. There are two reinforced webbing loops set into the sides at the top, positioned so that when you hold one in each hand you are pulling straight up the axis of the boot. Single back loops pull the boot backwards and make it harder, not easier. The calf opening is 15 inches around, which takes a trouser leg tucked in or a thick sock without a fight, and the shaft is 11 inches tall — high enough for wet grass and puddles, low enough to walk in comfortably. The body is moulded rubber in one piece with no stitched seam anywhere, so there is nothing to leak and nothing to unpick. Inside there is a brushed jersey lining that lets a foot slide in rather than sticking to bare rubber, and a removable 5 mm insole. Underneath, the outsole is both lugged and siped — 5 mm lugs to shed mud, fine slits cut across them to hold on wet paving. The heel has a defined square edge, which is what lets you get a boot off using the other foot. Rinse them under a tap and stand them upside down to dry.</p>
      </div>
    </section>

